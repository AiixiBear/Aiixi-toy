void show_wait_icon() {
  M5.Lcd.drawXBitmap(60, 22, wait_icon, wait_icon_width, wait_icon_height, txt_color, bg_color);
}

void clear_wait_icon() {
  M5.Lcd.fillRect(60, 22, wait_icon_width, wait_icon_height, bg_color);
}

void drawBattery() {
  // Cache the integer level: the toolbar tick calls this every loop, and
  // redrawing identical rectangles every iteration is wasted work. The
  // level also drives the low-battery colour, so a redraw on change
  // covers both.
  static int lastLevel = -1;
  int batteryLevelInt = (int)M5.Power.getBatteryLevel();
  if (batteryLevelInt == lastLevel) {
    return;
  }
  lastLevel = batteryLevelInt;
  float batteryLevel = (float)batteryLevelInt;

  // draw the outer base rectangle with white color, the inner rectangle with black color,
  // then fill the inner rectangle with greencolor with the battery level
  int batteryLevelWidth = (int)(batteryLevel / 100.0 * (battery_width - batt_border));

  int batt_x = screen_x - battery_width - batt_margin;
  int batt_y = batt_margin;

  int batt_color = batteryLevel < 20 ? TFT_RED : TFT_GREEN;

  M5.Lcd.drawRect(batt_x, batt_y, battery_width, battery_height, txt_color);
  M5.Lcd.fillRect(batt_x + 1, batt_y + 1, battery_width - batt_border, battery_height - batt_border, bg_color);

  M5.Lcd.fillRect(batt_x + 1, batt_y + 1, batteryLevelWidth, battery_height - batt_border, batt_color);

}

// Toolbar: current app name on the left, BT status and battery on the
// right. Only redraws the name when it changes, so the per-loop tick can
// call it freely. The name area is kept clear of the BT icon and battery
// on both screen sizes (battery starts at x=138 on the 160px screen).
void drawBTStatus();  // defined below; the toolbar calls it every tick
void drawAppToolbar() {
  static String lastName = "";
  if (currentAppName != lastName) {
    M5.Lcd.fillRect(0, 0, 120, toolbar_height, bg_color);
    M5.Lcd.setFont(&beta5pt7b);
    M5.Lcd.setTextColor(txt_color, bg_color);
    M5.Lcd.setCursor(3, 5);
    M5.Lcd.print(currentAppName);
    lastName = currentAppName;
  }
  drawBTStatus();
  drawBattery();
}

// Bluetooth icon in the toolbar, left of the battery. Shown only while a host
// is connected, so it doubles as the "can type codes now" indicator.
void drawBTStatus() {
  static int last_state = -1;

  int state = bleHidConnected() ? 1 : 0;
  if (state == last_state) {
    return;
  }
  last_state = state;

  int bt_x = screen_x - battery_width - batt_margin - bt_icon_width - 3;
  int bt_y = (toolbar_height - bt_icon_height) / 2;   // centred in the toolbar row

  if (state == 1) {
    M5.Lcd.drawXBitmap(bt_x, bt_y, BT_bits, bt_icon_width, bt_icon_height, txt_color, bg_color);
  } else {
    M5.Lcd.fillRect(bt_x, bt_y, bt_icon_width, bt_icon_height, bg_color);
  }
}

// Per-loop tick for an app: keeps button state fresh, powers off after
// the inactivity timeout, refreshes the toolbar, and reports whether the
// user asked to leave the app (BtnB held). Replaces the old
// switchscreen(), which cycled screens on a short BtnB press; screen
// switching is now the home screen's job.
bool appExitRequested() {
  unsigned long currentMillis = millis();
  if (currentMillis - previousMillis >= timeout_ScreenOn) {
    M5.Power.powerOff();
  }
  M5.update();
  drawAppToolbar();
  // Background WebUI tick: every app loop runs through here, so the
  // server keeps being served while any app is open.
  webuiBgTick();
  if (M5.BtnB.wasHold()) {
    previousMillis = currentMillis;
    return true;
  }
  return false;
}

